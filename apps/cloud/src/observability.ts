import {
  createDiagnosticEvent,
  type DiagnosticContext,
  type DiagnosticEvent,
} from "@syntila/protocol";

export interface CorrelationContext {
  requestId?: string;
  eventId?: string;
  workspaceId?: string;
  runId?: string;
  taskId?: string;
  attemptId?: string;
  assignmentId?: string;
  runtimeId?: string;
  workspaceRuntimeId?: string;
  workerId?: string;
}

const SECRET_KEY =
  /(secret|token|password|api[_-]?key|authorization|cookie|credential(?!profile|status|id)|bearer|user[_-]?code|private[_-]?key)/i;
const MAX_STRING_LENGTH = 512;
const MAX_ARRAY_LENGTH = 50;
const MAX_OBJECT_KEYS = 80;

export function requestIdFor(request: Request): string {
  // CF-Ray is generated by Cloudflare and survives forwarding the original
  // WebSocket upgrade Request to a Durable Object. It therefore provides the
  // correlation ID shared by the edge Worker and the Durable Object.
  const rayId = request.headers.get("cf-ray")?.trim();
  if (rayId && rayId.length <= 128) return rayId;
  const supplied = request.headers.get("x-request-id")?.trim();
  return supplied && supplied.length <= 128 ? supplied : crypto.randomUUID();
}

export function isTrustedOrigin(
  request: Request,
  configuredOrigins: readonly string[] = [],
): boolean {
  const origin = request.headers.get("origin")?.replace(/\/$/, "");
  if (!origin) return false;
  const requestOrigin = new URL(request.url).origin;
  if (new Set([requestOrigin, ...configuredOrigins]).has(origin)) return true;
  try {
    const parsed = new URL(origin);
    if (
      parsed.hostname === "localhost" ||
      parsed.hostname === "127.0.0.1" ||
      parsed.hostname === "[::1]"
    ) {
      return true;
    }
  } catch {
    // Malformed origin
  }
  return false;
}

export function isTrustedRealtimeOrigin(
  request: Request,
  configuredOrigins: readonly string[] = [],
): boolean {
  return isTrustedOrigin(request, configuredOrigins);
}

export function sanitizeDiagnostics(value: unknown, depth = 0): unknown {
  if (depth > 5) return "[depth limited]";
  if (typeof value === "string") {
    return value.length > MAX_STRING_LENGTH
      ? `${value.slice(0, MAX_STRING_LENGTH)}…`
      : value;
  }
  if (
    value === null ||
    typeof value === "number" ||
    typeof value === "boolean"
  ) {
    return value;
  }
  if (Array.isArray(value)) {
    return value
      .slice(0, MAX_ARRAY_LENGTH)
      .map((item) => sanitizeDiagnostics(item, depth + 1));
  }
  if (typeof value === "object") {
    const result: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value).slice(0, MAX_OBJECT_KEYS)) {
      result[key] = SECRET_KEY.test(key)
        ? "[redacted]"
        : sanitizeDiagnostics(item, depth + 1);
    }
    return result;
  }
  return `[${typeof value}]`;
}

export function structuredLogRecord(
  level: "debug" | "info" | "warn" | "error",
  message: string,
  correlation: CorrelationContext = {},
  details: Record<string, unknown> = {},
): Record<string, unknown> {
  return {
    timestamp: new Date().toISOString(),
    level,
    message,
    correlation: sanitizeDiagnostics(correlation),
    ...(Object.keys(details).length > 0
      ? { details: sanitizeDiagnostics(details) }
      : {}),
  };
}

export function logStructured(
  level: "debug" | "info" | "warn" | "error",
  message: string,
  correlation: CorrelationContext = {},
  details: Record<string, unknown> = {},
): void {
  const record = JSON.stringify(
    structuredLogRecord(level, message, correlation, details),
  );
  if (level === "error") console.error(record);
  else if (level === "warn") console.warn(record);
  else console.log(record);
}

/** Emits a privacy-safe, schema-versioned execution diagnostic event. */
export function logDiagnosticEvent(
  input: Omit<DiagnosticEvent, "schemaVersion" | "eventId" | "timestamp"> &
    Partial<Pick<DiagnosticEvent, "eventId" | "timestamp">>,
): DiagnosticEvent {
  const event = createDiagnosticEvent(input);
  logStructured(
    event.severity === "warning" ? "warn" : event.severity,
    "diagnostic.event",
    {
      requestId: event.requestId,
      eventId: event.eventId,
      workspaceId: event.workspaceId,
      runId: event.runId,
      taskId: event.taskId,
      attemptId: event.attemptId,
      assignmentId: event.assignmentId,
      workspaceRuntimeId: event.workspaceRuntimeId,
      workerId: event.workerId,
    },
    { event },
  );
  return event;
}

/** Best-effort boundary for lifecycle instrumentation. Telemetry must never
 * change assignment admission or execution when an upstream value is malformed. */
export function tryLogDiagnosticEvent(
  input: Omit<DiagnosticEvent, "schemaVersion" | "eventId" | "timestamp"> &
    Partial<Pick<DiagnosticEvent, "eventId" | "timestamp">>,
): DiagnosticEvent | null {
  try {
    return logDiagnosticEvent(input);
  } catch {
    return null;
  }
}

export interface TraceEventInput {
  traceStage: NonNullable<DiagnosticContext["traceStage"]>;
  requestId?: string;
  workspaceId?: string;
  workspaceRuntimeId?: string;
  runId?: string;
  taskId?: string;
  attemptId?: string;
  assignmentId?: string;
  workerId?: string;
  workerTypeId?: string;
  severity?: DiagnosticEvent["severity"];
  errorCode?: string;
  /** Elapsed time of the measured step, from a monotonic timer when possible. */
  durationMs?: number;
  context?: Omit<DiagnosticContext, "traceStage" | "monotonicMs">;
}

/**
 * Emits one latency-trace stage. Each event carries the wall-clock timestamp
 * (comparable across hosts after clock-offset correction) and an emitter-local
 * monotonic reading (comparable only within this isolate; Workers freeze
 * `performance.now()` between I/O, so treat it as coarse).
 *
 * Synchronous, allocation-light and never throws: trace failures must not
 * delay or alter command delivery.
 */
export function tryLogTraceEvent(input: TraceEventInput): void {
  try {
    const { traceStage, context, durationMs, severity, errorCode, ...ids } =
      input;
    // Workers use the Unix epoch as performance.timeOrigin. Keep the bounded
    // optional reading only where it fits; elapsed durations remain valid.
    const monotonicMs = Math.max(0, Math.round(performance.now()));
    tryLogDiagnosticEvent({
      ...ids,
      component: "cloud",
      operation: "assignment",
      stage: "trace",
      severity: severity ?? "info",
      ...(errorCode ? { errorCode } : {}),
      retryable: false,
      context: {
        ...context,
        traceStage,
        ...(Number.isFinite(monotonicMs) && monotonicMs <= 2_147_483_647
          ? { monotonicMs }
          : {}),
        ...(durationMs !== undefined
          ? { durationMs: Math.max(0, Math.round(durationMs)) }
          : {}),
      },
    });
  } catch {
    // Telemetry boundary.
  }
}

export function withRequestId(response: Response, requestId: string): Response {
  if (response.status === 101) return response;
  const headers = new Headers(response.headers);
  headers.set("x-request-id", requestId);
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}
